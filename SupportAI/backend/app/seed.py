def _weighted_choice(rng: random.Random, options):
    values, weights = zip(*options)
    return rng.choices(values, weights=weights, k=1)[0]


def _random_created(rng: random.Random, now: datetime) -> datetime:
    """Случайный момент за последние 30 дней: чаще недавние, по выходным реже."""
    while True:
        days_ago = int(rng.triangular(0, 30, 0))
        day = (now - timedelta(days=days_ago)).date()
        if day.weekday() >= 5 and rng.random() < 0.65:
            continue
        moment = datetime(
            day.year, day.month, day.day, rng.randint(5, 14), rng.randint(0, 59), rng.randint(0, 59),
            tzinfo=timezone.utc,
        )
        if moment < now - timedelta(minutes=20):
            return moment


